def oct_(x0, y0, x1, y1, k=0.3):
    """팔각 고리 — 둥근 글자(O · o · 0 …)를 각지게. k = 모서리 깎는 몫"""
    w, h = x1 - x0, y1 - y0; cx, cy = min(w, h) * k, min(w, h) * k
    return ('loop', [(x0 + cx, y0), (x1 - cx, y0), (x1, y0 + cy), (x1, y1 - cy), (x1 - cx, y1), (x0 + cx, y1), (x0, y1 - cy), (x0, y0 + cy)])

def arc_(x0, y0, x1, y1, keep, k=0.3):
    """팔각의 일부(열린 꺾은선) — keep = 남길 모서리 번호들(0=아래 오른쪽부터 반시계로 8칸)"""
    pts = oct_(x0, y0, x1, y1, k)[1]
    seq = [pts[i % 8] for i in keep]
    return seq

