#!/usr/bin/env python3
"""공장 드릴 셋의 타일(22×22)을 굽는다 → play/assets/tile/tile_m_drill.png · tile_m_drill_e.png · tile_m_drill_x.png

    python3 tools/mkdrills.py && python3 tools/sync-manifest.py

★ 예전 그림은 상자 밑에 짧은 비트가 달린 손드릴 아이콘이라 광산 기계로 읽히지 않았다(사용자 지적 2026-10-16).
  실제 광산 장비의 모양을 따른다 — 기계식 = 무한궤도 위 디젤 천공기(엔진 · 배기통 · 세운 피드 마스트 · 착암기 · 드릴 로드),
  전동 = 전동 점보(바퀴 차대 · 케이블 릴 · 전기함 · 유압 붐 끝의 가로 피드 빔 · 로드), 심층 = 작은 시추탑(데릭 · 크라운 블록 · 드로워크스 · 회전 테이블).
  돌아가는 비트 · 광맥 점선은 게임이 그린다(factory/tick drawWork) — 여기는 몸체만. 심층 드릴의 놓인 그림(1×2)은 factory/big 이 따로 그린다.
  바깥 윤곽 1칸은 자동(불투명 칸에 닿은 투명 칸) — 그래서 모양은 가장자리에서 1칸 띄운다.
"""
import os
from PIL import Image, ImageDraw

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'play', 'assets', 'tile')
TS = 22
LINE = (24, 22, 28, 255)


def canvas():
    im = Image.new('RGBA', (TS, TS), (0, 0, 0, 0))
    return im, ImageDraw.Draw(im)


def R(d, x0, y0, x1, y1, c): d.rectangle([x0, y0, x1, y1], fill=c)
def L(d, pts, c, w=1): d.line(pts, fill=c, width=w)
def P(d, x, y, c): d.point((x, y), fill=c)


def outline(im):
    px = im.load(); add = []
    for y in range(TS):
        for x in range(TS):
            if px[x, y][3]: continue
            if any(0 <= x + dx < TS and 0 <= y + dy < TS and px[x + dx, y + dy][3] and px[x + dx, y + dy] != LINE
                   for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1))):
                add.append((x, y))
    for q in add: px[q] = LINE
    return im


def tracks(d, x0, x1, y0):
    """무한궤도 — 둥근 끝 · 바퀴 셋 · 윗면 마디"""
    R(d, x0 + 1, y0, x1 - 1, y0 + 3, (58, 58, 64, 255)); R(d, x0, y0 + 1, x1, y0 + 2, (58, 58, 64, 255))
    for x in range(x0 + 1, x1, 2): P(d, x, y0, (96, 96, 104, 255))
    for wx in range(x0 + 2, x1 - 1, 4): R(d, wx, y0 + 1, wx + 1, y0 + 2, (128, 128, 136, 255))


def mech():
    """기계식 — 디젤 크롤러 천공기(오른쪽을 본다)"""
    im, d = canvas()
    tracks(d, 1, 14, 17)
    R(d, 2, 10, 12, 16, (196, 138, 42, 255))             # 엔진 덮개(광산 장비 황토색)
    R(d, 2, 10, 12, 10, (236, 182, 86, 255)); R(d, 2, 16, 12, 16, (138, 90, 26, 255))
    for x in (4, 6, 8): R(d, x, 12, x, 14, (90, 58, 20, 255))   # 흡기 그릴
    R(d, 10, 12, 11, 13, (250, 214, 120, 255))           # 작업등
    R(d, 3, 4, 4, 9, (70, 66, 64, 255)); R(d, 3, 4, 4, 4, (120, 114, 108, 255))   # 배기통
    L(d, [(12, 12), (15, 9)], (160, 108, 34, 255), 2)     # 붐 — 몸에서 마스트로
    R(d, 15, 1, 17, 19, (176, 124, 38, 255)); R(d, 15, 1, 15, 19, (228, 172, 80, 255))   # 피드 마스트
    R(d, 14, 5, 18, 8, (176, 52, 40, 255)); R(d, 14, 5, 18, 5, (226, 96, 76, 255))       # 착암기(위에서 눌러 친다)
    R(d, 16, 9, 16, 19, (196, 200, 208, 255))           # 드릴 로드
    R(d, 15, 19, 17, 20, (232, 236, 242, 255)); P(d, 16, 20, (150, 154, 162, 255))       # 비트 — 땅에 박힌다
    return outline(im)


def elec():
    """전동 — 전동 점보(케이블 릴 · 유압 붐 · 가로 피드 빔, 오른쪽으로 뚫는다)"""
    im, d = canvas()
    R(d, 2, 13, 15, 16, (58, 104, 168, 255)); R(d, 2, 13, 15, 13, (110, 156, 214, 255))   # 차대
    for x in range(3, 15, 2): P(d, x, 16, (240, 200, 40, 255))                             # 범퍼 경고 띠
    for x in range(4, 15, 2): P(d, x, 16, (30, 30, 34, 255))
    for cx in (5, 12):                                                                     # 바퀴
        d.ellipse([cx - 3, 15, cx + 3, 20], fill=(46, 46, 52, 255)); R(d, cx - 1, 17, cx, 18, (140, 140, 150, 255))
    d.ellipse([1, 6, 7, 12], fill=(70, 70, 78, 255)); d.ellipse([2, 7, 6, 11], fill=(214, 120, 40, 255))   # 케이블 릴
    R(d, 3, 8, 5, 10, (150, 80, 24, 255)); P(d, 4, 9, (60, 60, 66, 255))
    R(d, 8, 7, 12, 12, (74, 124, 190, 255)); R(d, 8, 7, 12, 7, (130, 176, 230, 255))     # 전기함
    R(d, 9, 9, 10, 10, (120, 230, 255, 255))                                               # 표시등
    L(d, [(12, 11), (16, 7)], (100, 104, 112, 255), 2)                                     # 유압 붐
    L(d, [(13, 12), (16, 9)], (190, 196, 204, 255), 1)                                     # 실린더 로드
    R(d, 14, 4, 20, 6, (240, 196, 40, 255)); R(d, 14, 6, 20, 6, (170, 130, 20, 255))      # 피드 빔(노랑)
    R(d, 14, 3, 16, 7, (58, 104, 168, 255)); R(d, 14, 3, 16, 3, (120, 170, 226, 255))     # 착암기
    R(d, 17, 5, 20, 5, (200, 204, 212, 255)); P(d, 20, 4, (236, 240, 246, 255)); P(d, 20, 6, (236, 240, 246, 255))   # 로드 · 비트
    return outline(im)


def deep():
    """심층 — 작은 시추탑(데릭) · 가압판 드로워크스"""
    im, d = canvas()
    TEAL, TEAL_LT, TEAL_DK, STEEL = (46, 90, 90, 255), (90, 150, 146, 255), (30, 58, 58, 255), (150, 176, 176, 255)
    for (a, b) in (((4, 19), (9, 3)), ((17, 19), (12, 3))):                                # 탑 다리
        L(d, [a, b], STEEL, 1)
    for y in range(6, 19, 4):                                                              # 가새
        k0, k1 = (y - 3) / 16, (y + 4 - 3) / 16
        xl0, xr0 = 9 - k0 * 5, 12 + k0 * 5; xl1, xr1 = 9 - min(1, k1) * 5, 12 + min(1, k1) * 5
        L(d, [(round(xl0), y), (round(xr1), min(19, y + 4))], (110, 134, 134, 255), 1)
        L(d, [(round(xr0), y), (round(xl1), min(19, y + 4))], (110, 134, 134, 255), 1)
    R(d, 8, 1, 13, 3, (64, 70, 76, 255)); R(d, 9, 1, 12, 1, (150, 160, 168, 255))         # 크라운 블록
    R(d, 10, 4, 11, 19, (196, 200, 208, 255))                                              # 드릴 스트링
    R(d, 9, 9, 12, 11, (230, 180, 60, 255))                                                # 트래블링 블록
    R(d, 6, 18, 15, 20, TEAL); R(d, 6, 18, 15, 18, TEAL_LT)                                # 회전 테이블 · 받침
    R(d, 1, 14, 6, 20, TEAL); R(d, 1, 14, 6, 14, TEAL_LT); R(d, 1, 20, 6, 20, TEAL_DK)    # 드로워크스(가압판)
    for q in ((1, 15), (6, 15), (1, 19), (6, 19)): P(d, *q, (200, 236, 230, 255))          # 리벳
    R(d, 3, 16, 4, 17, (127, 232, 224, 255))                                               # 창 — 청록 불
    return outline(im)


def main():
    for name, fn in (('m_drill', mech), ('m_drill_e', elec), ('m_drill_x', deep)):
        im = fn(); im.save(os.path.join(OUT, f'tile_{name}.png'), optimize=True)
        print(f'tile_{name}.png', im.size)


if __name__ == '__main__':
    main()
