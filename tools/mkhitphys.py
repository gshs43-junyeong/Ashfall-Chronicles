MARGIN = 2              # 틀 안쪽에 반드시 남는 여백(원본 px) — 단면이 안 생기는 최소치

# 굽는 동안 바뀌는 것: 재는 판(CANV=128)과 내는 판(CANV=64), 그리고 틀 맞춤 배율.
CANV, CEN, FIT = N, N / 2, 1.0

W = (255, 246, 224)     # 심지 — 따뜻한 흰빛
G = (255, 224, 138)     # 금빛 몸통
